-- P1.7 one-time Snowflake setup.
-- Run deliberately in Snowsight as a user allowed to use ACCOUNTADMIN.
-- The script creates only an X-Small warehouse, one database, two schemas,
-- one RAW table, two least-privilege roles, and a one-credit monthly monitor.

-- A new trial account may grant ACCOUNTADMIN to its first user without making
-- every subordinate system role directly usable in that session. Provision
-- once as ACCOUNTADMIN, then grant only the narrow permissions below to the
-- two runtime roles. Neither runtime role inherits ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS SAI_REVENUEOS_LOADER;
CREATE ROLE IF NOT EXISTS SAI_REVENUEOS_DBT;
GRANT ROLE SAI_REVENUEOS_LOADER TO ROLE ACCOUNTADMIN;
GRANT ROLE SAI_REVENUEOS_DBT TO ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS SAI_REVENUEOS_XS
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 1
    COMMENT = 'SAI RevenueOS P1.7 learning warehouse';
ALTER WAREHOUSE SAI_REVENUEOS_XS SET
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 1
    STATEMENT_TIMEOUT_IN_SECONDS = 300;

CREATE DATABASE IF NOT EXISTS SAI_REVENUEOS
    COMMENT = 'SAI RevenueOS learning database; fictional test data only';
CREATE SCHEMA IF NOT EXISTS SAI_REVENUEOS.RAW WITH MANAGED ACCESS
    COMMENT = 'Immutable P1.3/P1.6 source-event copies';
CREATE SCHEMA IF NOT EXISTS SAI_REVENUEOS.STAGING WITH MANAGED ACCESS
    COMMENT = 'dbt-created normalized source views';

CREATE TABLE IF NOT EXISTS SAI_REVENUEOS.RAW.SOURCE_EVENT (
    EVENT_ID VARCHAR NOT NULL,
    CONTRACT_VERSION VARCHAR NOT NULL,
    SOURCE_SYSTEM VARCHAR NOT NULL,
    SOURCE_TENANT VARCHAR NOT NULL,
    SOURCE_OBJECT_TYPE VARCHAR NOT NULL,
    SOURCE_OBJECT_ID VARCHAR NOT NULL,
    EVENT_TYPE VARCHAR NOT NULL,
    SOURCE_UPDATED_AT VARCHAR NOT NULL,
    OBSERVED_AT VARCHAR NOT NULL,
    TRACE_ID VARCHAR NOT NULL,
    EXTRACTION_ID VARCHAR NOT NULL,
    STREAM_NAME VARCHAR NOT NULL,
    CHECKPOINT_CURSOR VARCHAR NOT NULL,
    CHECKPOINT_HIGH_WATERMARK_AT VARCHAR NOT NULL,
    RAW_PAYLOAD_JSON VARIANT NOT NULL,
    PAYLOAD_SHA256 VARCHAR NOT NULL,
    ENVELOPE_SHA256 VARCHAR NOT NULL,
    PROCESSING_STATUS VARCHAR NOT NULL,
    PROCESSING_ATTEMPTS NUMBER NOT NULL,
    LAST_ERROR_TYPE VARCHAR,
    LAST_ERROR_MESSAGE VARCHAR,
    SOURCE_RECORD_ID VARCHAR,
    BECAME_CURRENT BOOLEAN,
    RECEIVED_AT VARCHAR NOT NULL,
    PROCESSED_AT VARCHAR,
    LOAD_BATCH_ID VARCHAR NOT NULL,
    LOADED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Immutable copies of the complete local source-event envelopes';

CREATE RESOURCE MONITOR IF NOT EXISTS SAI_REVENUEOS_MONTHLY_LIMIT
    WITH CREDIT_QUOTA = 1
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 50 PERCENT DO NOTIFY
        ON 75 PERCENT DO SUSPEND
        ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE SAI_REVENUEOS_XS
    SET RESOURCE_MONITOR = SAI_REVENUEOS_MONTHLY_LIMIT;

GRANT USAGE ON WAREHOUSE SAI_REVENUEOS_XS TO ROLE SAI_REVENUEOS_LOADER;
GRANT USAGE ON WAREHOUSE SAI_REVENUEOS_XS TO ROLE SAI_REVENUEOS_DBT;
GRANT USAGE ON DATABASE SAI_REVENUEOS TO ROLE SAI_REVENUEOS_LOADER;
GRANT USAGE ON DATABASE SAI_REVENUEOS TO ROLE SAI_REVENUEOS_DBT;
GRANT USAGE ON SCHEMA SAI_REVENUEOS.RAW TO ROLE SAI_REVENUEOS_LOADER;
GRANT USAGE ON SCHEMA SAI_REVENUEOS.RAW TO ROLE SAI_REVENUEOS_DBT;
GRANT USAGE ON SCHEMA SAI_REVENUEOS.STAGING TO ROLE SAI_REVENUEOS_DBT;
GRANT CREATE TABLE ON SCHEMA SAI_REVENUEOS.RAW TO ROLE SAI_REVENUEOS_LOADER;
GRANT SELECT, INSERT ON TABLE SAI_REVENUEOS.RAW.SOURCE_EVENT TO ROLE SAI_REVENUEOS_LOADER;
GRANT SELECT ON TABLE SAI_REVENUEOS.RAW.SOURCE_EVENT TO ROLE SAI_REVENUEOS_DBT;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA SAI_REVENUEOS.STAGING TO ROLE SAI_REVENUEOS_DBT;
GRANT MONITOR ON RESOURCE MONITOR SAI_REVENUEOS_MONTHLY_LIMIT TO ROLE SAI_REVENUEOS_LOADER;
GRANT MONITOR ON RESOURCE MONITOR SAI_REVENUEOS_MONTHLY_LIMIT TO ROLE SAI_REVENUEOS_DBT;

-- Verify the guardrails before running a load.
SHOW WAREHOUSES LIKE 'SAI_REVENUEOS_XS';
SHOW RESOURCE MONITORS LIKE 'SAI_REVENUEOS_MONTHLY_LIMIT';
SHOW GRANTS TO ROLE SAI_REVENUEOS_LOADER;
SHOW GRANTS TO ROLE SAI_REVENUEOS_DBT;
