-- P1.7 local programmatic authentication setup.
-- Run the setup section once as ACCOUNTADMIN. It creates two service users,
-- restricts each to one role, and applies a network policy containing only the
-- current client IPv4 address. It does not weaken account-wide authentication.

USE ROLE ACCOUNTADMIN;

SET SAI_P17_CLIENT_IP = CURRENT_IP_ADDRESS();
SET SAI_P17_CREATE_NETWORK_POLICY_SQL =
    'CREATE NETWORK POLICY IF NOT EXISTS SAI_REVENUEOS_LOCAL_PAT_POLICY '
    || 'ALLOWED_IP_LIST = (''' || $SAI_P17_CLIENT_IP || ''') '
    || 'COMMENT = ''Restrict P1.7 service tokens to the authorized local connection''';
EXECUTE IMMEDIATE $SAI_P17_CREATE_NETWORK_POLICY_SQL;
SET SAI_P17_UPDATE_NETWORK_POLICY_SQL =
    'ALTER NETWORK POLICY SAI_REVENUEOS_LOCAL_PAT_POLICY '
    || 'SET ALLOWED_IP_LIST = (''' || $SAI_P17_CLIENT_IP || ''')';
EXECUTE IMMEDIATE $SAI_P17_UPDATE_NETWORK_POLICY_SQL;

CREATE USER IF NOT EXISTS SAI_REVENUEOS_LOADER_SVC
    TYPE = SERVICE
    DEFAULT_ROLE = SAI_REVENUEOS_LOADER
    DEFAULT_WAREHOUSE = SAI_REVENUEOS_XS
    DEFAULT_NAMESPACE = 'SAI_REVENUEOS.RAW'
    COMMENT = 'P1.7 RAW loader; no human login';

CREATE USER IF NOT EXISTS SAI_REVENUEOS_DBT_SVC
    TYPE = SERVICE
    DEFAULT_ROLE = SAI_REVENUEOS_DBT
    DEFAULT_WAREHOUSE = SAI_REVENUEOS_XS
    DEFAULT_NAMESPACE = 'SAI_REVENUEOS.STAGING'
    COMMENT = 'P1.7 dbt Core runner; no human login';

ALTER USER SAI_REVENUEOS_LOADER_SVC
    SET NETWORK_POLICY = SAI_REVENUEOS_LOCAL_PAT_POLICY;
ALTER USER SAI_REVENUEOS_DBT_SVC
    SET NETWORK_POLICY = SAI_REVENUEOS_LOCAL_PAT_POLICY;

GRANT ROLE SAI_REVENUEOS_LOADER TO USER SAI_REVENUEOS_LOADER_SVC;
GRANT ROLE SAI_REVENUEOS_DBT TO USER SAI_REVENUEOS_DBT_SVC;

-- Run each token statement separately. Snowflake displays each secret once.
-- Copy it directly into configure_snowflake_auth.py; never paste it into chat.
ALTER USER SAI_REVENUEOS_LOADER_SVC
    ADD PROGRAMMATIC ACCESS TOKEN IF NOT EXISTS SAI_REVENUEOS_LOADER_PAT
    ROLE_RESTRICTION = 'SAI_REVENUEOS_LOADER'
    DAYS_TO_EXPIRY = 30
    COMMENT = 'P1.7 local RAW loader; rotate every 30 days';

ALTER USER SAI_REVENUEOS_DBT_SVC
    ADD PROGRAMMATIC ACCESS TOKEN IF NOT EXISTS SAI_REVENUEOS_DBT_PAT
    ROLE_RESTRICTION = 'SAI_REVENUEOS_DBT'
    DAYS_TO_EXPIRY = 30
    COMMENT = 'P1.7 local dbt Core runner; rotate every 30 days';

SHOW USER PROGRAMMATIC ACCESS TOKENS FOR USER SAI_REVENUEOS_LOADER_SVC;
SHOW USER PROGRAMMATIC ACCESS TOKENS FOR USER SAI_REVENUEOS_DBT_SVC;
