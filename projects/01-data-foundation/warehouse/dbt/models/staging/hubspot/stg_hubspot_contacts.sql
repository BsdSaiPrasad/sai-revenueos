select
    event_id,
    source_record_id,
    source_system,
    source_tenant,
    source_object_type,
    source_object_id,
    nullif(trim(raw_payload_json:id::string), '') as payload_source_object_id,
    nullif(trim(raw_payload_json:properties:firstname::string), '') as first_name,
    nullif(trim(raw_payload_json:properties:lastname::string), '') as last_name,
    nullif(lower(trim(raw_payload_json:properties:email::string)), '') as email,
    nullif(trim(raw_payload_json:properties:associatedcompanyid::string), '') as account_source_object_id,
    nullif(trim(raw_payload_json:properties:jobtitle::string), '') as job_title,
    event_type,
    is_deleted,
    source_updated_at,
    observed_at,
    received_at,
    is_latest_source_version,
    is_late_arriving,
    trace_id,
    extraction_id,
    checkpoint_cursor,
    payload_sha256,
    envelope_sha256,
    raw_payload_json,
    loaded_at
from {{ ref('stg_source_events') }}
where source_system = 'hubspot' and source_object_type = 'Contact'
