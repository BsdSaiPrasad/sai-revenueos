    event_id,
    source_record_id,
    source_system,
    source_tenant,
    source_object_type,
    source_object_id,
    nullif(trim(raw_payload_json:Id::string), '') as payload_source_object_id,
    nullif(trim(raw_payload_json:Name::string), '') as name,
    nullif(trim(raw_payload_json:Website::string), '') as domain,
    nullif(trim(raw_payload_json:Industry::string), '') as industry,
    nullif(trim(raw_payload_json:BillingCountry::string), '') as country,
    nullif(trim(raw_payload_json:OwnerId::string), '') as owner_id,
    event_type,
    is_deleted,
    source_updated_at,
    observed_at,
    received_at,
    is_latest_source_version,
    is_late_arriving,
    trace_id,
    extraction_id,
    checkpoint_cursor,
    payload_sha256,
    envelope_sha256,
    raw_payload_json,
    loaded_at
