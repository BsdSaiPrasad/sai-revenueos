select
    event_id,
    source_record_id,
    source_system,
    source_tenant,
    source_object_type,
    source_object_id,
    nullif(trim(raw_payload_json:Id::string), '') as payload_source_object_id,
    nullif(trim(raw_payload_json:FirstName::string), '') as first_name,
    nullif(trim(raw_payload_json:LastName::string), '') as last_name,
    nullif(lower(trim(raw_payload_json:Email::string)), '') as email,
    nullif(trim(raw_payload_json:Company::string), '') as company_name,
    nullif(trim(raw_payload_json:Status::string), '') as lead_status,
    nullif(trim(raw_payload_json:ConvertedContactId::string), '') as converted_contact_id,
    event_type,
    is_deleted,
    source_updated_at,
    observed_at,
    received_at,
    is_latest_source_version,
    is_late_arriving,
    trace_id,
    extraction_id,
    checkpoint_cursor,
    payload_sha256,
    envelope_sha256,
    raw_payload_json,
    loaded_at
from {{ ref('stg_source_events') }}
where source_system = 'salesforce' and source_object_type = 'Lead'
